using System.Globalization;

namespace DashDeck.Core.Updates;

/// <summary>Why an update must not be installed. <see cref="None"/> is the only one that proceeds.</summary>
public enum InstallRefusal
{
    /// <summary>Nothing is in the way.</summary>
    None,

    /// <summary>The running folder is not a deploy — no executable beside us.</summary>
    NotADeploy,

    /// <summary>Running from a build output. Replacing that folder would fight the compiler.</summary>
    DevelopmentBuild,

    /// <summary>The downloaded archive does not contain a DashDeck.</summary>
    ArchiveNotDashDeck,

    /// <summary>Not enough free disk for the archive, the staged copy and the kept previous one.</summary>
    NotEnoughRoom,

    /// <summary>The download did not finish, or finished the wrong size.</summary>
    ArchiveIncomplete,
}

/// <summary>
/// The questions asked before a folder swap, each of which has a wrong answer that ends with a
/// dash that will not start.
/// </summary>
/// <remarks>
/// Separated from the file system on purpose: the caller gathers the facts and this decides, so
/// the decision is testable without creating a 300 MB fixture or a fake Windows. The facts are
/// deliberately dull — does the executable exist, how many bytes are free — because every
/// interesting failure here is a judgement about those dull facts.
/// <para>
/// The room requirement is <b>three times</b> the archive: the zip, the extracted copy, and the
/// previous folder that is kept rather than deleted. Keeping the old folder is what makes a bad
/// swap survivable in a parking lot, so the space for it is not optional.
/// </para>
/// </remarks>
public static class InstallGuards
{
    /// <summary>How many copies of the archive's worth of bytes must be free.</summary>
    public const int RoomMultiplier = 3;

    /// <summary>Decide whether a swap may go ahead.</summary>
    /// <param name="runningFolder">Where the executable lives now.</param>
    /// <param name="hasExecutable">Whether <c>DashDeck.Host.exe</c> is in it.</param>
    /// <param name="archiveBytes">The size the release said the archive is.</param>
    /// <param name="downloadedBytes">The size actually on disk.</param>
    /// <param name="archiveHoldsDashDeck">Whether the archive contains the executable.</param>
    /// <param name="freeBytes">Free space on the volume the folder is on.</param>
    public static InstallRefusal Check(
        string runningFolder,
        bool hasExecutable,
        long archiveBytes,
        long downloadedBytes,
        bool archiveHoldsDashDeck,
        long freeBytes)
    {
        // A build output is the one folder that must never be swapped: it is regenerated by the
        // compiler, it is inside a git checkout, and whoever is running it has a terminal.
        if (LooksLikeBuildOutput(runningFolder))
        {
            return InstallRefusal.DevelopmentBuild;
        }

        if (!hasExecutable)
        {
            return InstallRefusal.NotADeploy;
        }

        if (downloadedBytes <= 0 || (archiveBytes > 0 && downloadedBytes != archiveBytes))
        {
            return InstallRefusal.ArchiveIncomplete;
        }

        if (!archiveHoldsDashDeck)
        {
            return InstallRefusal.ArchiveNotDashDeck;
        }

        return freeBytes < downloadedBytes * RoomMultiplier
            ? InstallRefusal.NotEnoughRoom
            : InstallRefusal.None;
    }

    /// <summary>Whether a path is somewhere a compiler owns.</summary>
    public static bool LooksLikeBuildOutput(string folder)
    {
        var path = folder.Replace('/', '\\');

        return path.Contains("\\bin\\", StringComparison.OrdinalIgnoreCase)
            || path.Contains("\\obj\\", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith("\\bin", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith("\\obj", StringComparison.OrdinalIgnoreCase);
    }

    /// <summary>What to put on screen when a swap is refused, in the person's terms.</summary>
    public static string Explain(InstallRefusal refusal, long downloadedBytes = 0) => refusal switch
    {
        InstallRefusal.None => "",
        InstallRefusal.DevelopmentBuild =>
            "This is running from a build folder, which the compiler owns. Update the deployed "
                + "copy instead, or run publish.ps1.",
        InstallRefusal.NotADeploy =>
            "DashDeck.Host.exe is not beside this build, so there is no folder to replace.",
        InstallRefusal.ArchiveNotDashDeck =>
            "The downloaded file is not a DashDeck deploy — it has no DashDeck.Host.exe in it.",
        InstallRefusal.ArchiveIncomplete =>
            "The download did not finish. Check the connection and fetch it again.",
        InstallRefusal.NotEnoughRoom =>
            $"Not enough free space. The swap needs about {Megabytes(downloadedBytes * RoomMultiplier)} MB — "
                + "the archive, the new copy, and the old one kept in case it is needed.",
        _ => "Refused.",
    };

    private static string Megabytes(long bytes) =>
        (bytes / 1048576.0).ToString("0", CultureInfo.InvariantCulture);
}
